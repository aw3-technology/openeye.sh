/**
 * Copy text, resolving to whether it worked.
 *
 * `navigator.clipboard.writeText` rejects with NotAllowedError when the page
 * is framed without `clipboard-write`, the document isn't focused, or the
 * browser (Safari, some Chromium policies) denies it. The old
 * `execCommand("copy")` on a selected textarea still works in most of those
 * cases, so try that before giving up.
 */
export async function copyText(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {
    // Fall through to the legacy path.
  }
  return legacyCopy(text);
}

function legacyCopy(text: string): boolean {
  if (typeof document === "undefined") return false;
  const area = document.createElement("textarea");
  area.value = text;
  area.setAttribute("readonly", "");
  area.style.cssText = "position:fixed;top:0;left:0;opacity:0;pointer-events:none;";
  const active = document.activeElement as HTMLElement | null;
  document.body.appendChild(area);
  area.select();
  let ok = false;
  try {
    ok = document.execCommand("copy");
  } catch {
    ok = false;
  }
  area.remove();
  active?.focus?.();
  return ok;
}
